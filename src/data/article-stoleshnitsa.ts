const SAMPLE_ALT: Record<StoneGroup, string> = {
  Мрамор: "мрамора",
  Гранит: "гранита",
  Кварцит: "кварцита",
  Оникс: "оникса",
  Травертин: "травертина",
};

function portfolioImage(id: string, alt: string): ArticleImage {
  const item = PORTFOLIO_ITEMS.find((entry) => entry.id === id);
  if (!item) throw new Error(`В портфолио нет фото ${id}`);
  return { src: item.src, alt };
}

function sample(name: string, group: StoneGroup): ArticleSample {
  const stone = STONES.find((entry) => entry.name === name && entry.group === group);
  if (!stone?.imageSrc) throw new Error(`В каталоге нет камня ${group} «${name}»`);
  return {
    name: stone.name,
    group: stone.group,
    imageSrc: stone.imageSrc,
    alt: `${stone.name} — образец ${SAMPLE_ALT[stone.group]}`,
  };
}

function serviceCardByPath(path: string): ArticleServiceCard {
  const slug = path.replace(/^\/uslugi\//, "");
  const copy = SERVICE_COPY.find((item) => item.slug === slug);
  const service = SERVICES.find((item) => item.id === copy?.serviceId);
  if (!copy || !service) throw new Error(`Нет услуги ${path}`);
  return { path, title: copy.h1, description: service.description };
}

